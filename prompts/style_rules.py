def sponsor_instruction(sponsor_type: str) -> str:
    """협찬 유형에 따라 글 첫머리 처리 지침을 돌려준다."""
    notice = SPONSOR_NOTICES.get(sponsor_type, "")
    if sponsor_type == "내돈내산":
        return (
            "[협찬 표기] 이 글은 '내돈내산'이다. 상단 고지 문구는 넣지 말고, "
            "제목이나 본문 초반에 직접 구매했다는 점을 자연스럽게 드러내라."
        )
    if notice:
        return (
            f"[협찬 표기] 이 글은 '{sponsor_type}' 후기다. 본문 맨 위 첫 줄에 다음 고지 "
            f'문구를 반드시 넣어라(별도 문단으로): "{notice}"'
        )
    return "[협찬 표기] 협찬 정보가 명확하지 않다. '확인 필요'에 협찬 문구 항목을 넣어라."
